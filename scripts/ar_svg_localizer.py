_TAG_RE = re.compile(r"(<(?:text|tspan)[^>]*>)([^<]+)(</(?:text|tspan)>)")


def localize_svg_to_ar(svg: str) -> str:
    """Translate known English <text>/<tspan> labels into Arabic while preserving XML validity."""
    if not svg or "<svg" not in svg:
        return svg

    def _repl(m: re.Match) -> str:
        open_tag, body, close_tag = m.group(1), m.group(2), m.group(3)
        stripped = body.strip()
        if stripped in AR_SVG_TEXT_MAP:
            ar_txt = AR_SVG_TEXT_MAP[stripped]
            # Escape & if not already XML entity
            ar_txt = re.sub(r"&(?!amp;|lt;|gt;|quot;|apos;|#)", "&amp;", ar_txt)
            return f"{open_tag}{ar_txt}{close_tag}"
        return m.group(0)

    out = _TAG_RE.sub(_repl, svg)
    ET.fromstring(out)
    return out
